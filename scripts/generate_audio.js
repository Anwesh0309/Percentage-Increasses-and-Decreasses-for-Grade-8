/* =========================================================================
   OFFLINE AUDIO GENERATION — Complete 239/239 Coverage
   Usage:  node scripts/generate_audio.js
   • Reads all phrases from src/utils/lessonScript.js
   • Enhances mathematical pronunciation for TTS ($, %, ×, ÷, −, ², ³)
   • Generates MP3s into public/assets/audio/ and writes src/utils/audioMap.js
   • Uses ElevenLabs when quota allows, and MsEdgeTTS (Azure Neural) seamlessly
     to ensure 100% of all 239 audio files exist as high-fidelity MP3s.
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { ALL_PHRASES } from '../src/utils/lessonScript.js';
import { MsEdgeTTS, OUTPUT_FORMAT } from 'msedge-tts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'audio');
const MAP_FILE = path.join(ROOT, 'src', 'utils', 'audioMap.js');

const VOICE_ID = 'Xb7hH8MSUJpSbSDYk0k2';
const MODEL_ID = 'eleven_multilingual_v2';

const STYLE_SETTINGS = {
  celebration:   { stability: 0.12, similarity_boost: 0.45, style: 0.75, use_speaker_boost: true },
  encouragement: { stability: 0.16, similarity_boost: 0.50, style: 0.65, use_speaker_boost: true },
  question:      { stability: 0.20, similarity_boost: 0.55, style: 0.55, use_speaker_boost: true },
  emphasis:      { stability: 0.16, similarity_boost: 0.50, style: 0.60, use_speaker_boost: true },
  thinking:      { stability: 0.24, similarity_boost: 0.60, style: 0.35, use_speaker_boost: true },
  statement:     { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true },
  instruction:   { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true }
};

function readEnvKey() {
  if (process.env.VITE_ELEVENLABS_API_KEY) return process.env.VITE_ELEVENLABS_API_KEY;
  for (const f of ['.env.local', '.env']) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    const m = fs.readFileSync(p, 'utf8').match(/^\s*VITE_ELEVENLABS_API_KEY\s*=\s*"?([^"\r\n]+)"?/m);
    if (m) return m[1].trim();
  }
  return '';
}

const slugify = text =>
  text.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 50);

const sleep = ms => new Promise(r => setTimeout(r, ms));

function cleanForSpeech(text) {
  return text
    .replace(/\$(\d+[\d,]*(\.\d+)?)/g, '$1 dollars')
    .replace(/(\d+)%/g, '$1 percent')
    .replace(/−/g, ' minus ')
    .replace(/÷/g, ' divided by ')
    .replace(/×/g, ' times ')
    .replace(/²/g, ' squared')
    .replace(/³/g, ' cubed')
    .replace(/\s+/g, ' ')
    .trim();
}

function writeMapFile(map) {
  const out =
    '/* =========================================================================\n' +
    '   AUTO-GENERATED by scripts/generate_audio.js — do not edit by hand.\n' +
    '   Key: exact spoken text  →  Value: pre-generated MP3 path.\n' +
    '   ========================================================================= */\n' +
    `export const audioMap = ${JSON.stringify(map, null, 2)};\n`;
  fs.writeFileSync(MAP_FILE, out);
}

async function generateMsEdge(text, filePath) {
  const tts = new MsEdgeTTS();
  await tts.setMetadata('en-US-JennyNeural', OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3);
  const { audioStream } = tts.toStream(text);
  const chunks = [];
  return new Promise((resolve, reject) => {
    audioStream.on('data', chunk => chunks.push(chunk));
    audioStream.on('end', () => {
      const buf = Buffer.concat(chunks);
      fs.writeFileSync(filePath, buf);
      resolve(buf.length);
    });
    audioStream.on('error', reject);
  });
}

async function main() {
  const force = process.argv.includes('--force');
  const apiKey = readEnvKey();
  fs.mkdirSync(OUT_DIR, { recursive: true });

  // Read existing map if present
  let map = {};
  if (fs.existsSync(MAP_FILE)) {
    try {
      const existingContent = fs.readFileSync(MAP_FILE, 'utf8');
      const jsonMatch = existingContent.match(/audioMap\s*=\s*(\{[\s\S]*?\});/);
      if (jsonMatch) map = JSON.parse(jsonMatch[1]);
    } catch (e) {}
  }

  // De-duplicate phrases by exact text
  const seen = new Set();
  const phrases = ALL_PHRASES.filter(p => {
    if (!p.text || seen.has(p.text)) return false;
    seen.add(p.text);
    return true;
  });

  console.log(`Starting audio generation for ${phrases.length} phrases...`);
  let made = 0, skipped = 0, fallbackMade = 0;

  for (let i = 0; i < phrases.length; i++) {
    const p = phrases[i];
    const hash = crypto.createHash('md5').update(p.text).digest('hex').slice(0, 6);
    const fileName = `audio_${slugify(p.text)}_${hash}.mp3`;
    const filePath = path.join(OUT_DIR, fileName);
    const publicPath = `/assets/audio/${fileName}`;

    if (!force && fs.existsSync(filePath) && fs.statSync(filePath).size > 0) {
      map[p.text] = publicPath;
      skipped++;
      continue;
    }

    const spokenText = cleanForSpeech(p.text);
    const s = STYLE_SETTINGS[p.style] || STYLE_SETTINGS.statement;
    let generated = false;

    // 1. Try ElevenLabs if apiKey is present
    if (apiKey) {
      try {
        const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
          method: 'POST',
          headers: {
            'xi-api-key': apiKey,
            'Content-Type': 'application/json',
            Accept: 'audio/mpeg'
          },
          body: JSON.stringify({
            text: spokenText,
            model_id: MODEL_ID,
            voice_settings: s
          })
        });

        if (res.ok) {
          const buf = Buffer.from(await res.arrayBuffer());
          fs.writeFileSync(filePath, buf);
          map[p.text] = publicPath;
          made++;
          generated = true;
          console.log(`[${i + 1}/${phrases.length}] (ElevenLabs) ✔ ${p.text.slice(0, 45)}…`);
        }
      } catch (e) {}
    }

    // 2. Seamless neural fallback via MsEdgeTTS if ElevenLabs is unavailable or quota exceeded
    if (!generated) {
      try {
        const bytes = await generateMsEdge(spokenText, filePath);
        map[p.text] = publicPath;
        fallbackMade++;
        console.log(`[${i + 1}/${phrases.length}] (Neural TTS) ✔ ${p.text.slice(0, 45)}… (${bytes} bytes)`);
      } catch (err) {
        console.error(`[${i + 1}/${phrases.length}] ✖ Failed ${p.text.slice(0, 45)}…: ${err.message}`);
      }
    }

    await sleep(80);
    if ((i + 1) % 15 === 0) writeMapFile(map);
  }

  writeMapFile(map);

  console.log(`\n======================================================`);
  console.log(`All audio narrations generated:`);
  console.log(`  - Reused existing:    ${skipped}`);
  console.log(`  - ElevenLabs new:     ${made}`);
  console.log(`  - Neural fallback:    ${fallbackMade}`);
  console.log(`  - Total in audioMap:  ${Object.keys(map).length} / ${phrases.length}`);
  console.log(`======================================================\n`);
}

main();
