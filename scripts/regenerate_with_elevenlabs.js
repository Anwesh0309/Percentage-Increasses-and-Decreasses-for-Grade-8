/* =========================================================================
   REGENERATE FALLBACK PHRASES WITH ELEVENLABS ALICE
   Uses new API key from .env.local and Voice ID: Xb7hH8MSUJpSbSDYk0k2
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { ALL_PHRASES } from '../src/utils/lessonScript.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'audio');
const MAP_FILE = path.join(ROOT, 'src', 'utils', 'audioMap.js');

const VOICE_ID = 'Xb7hH8MSUJpSbSDYk0k2';
const MODEL_ID = 'eleven_multilingual_v2';

const STYLE_SETTINGS = {
  celebration:   { stability: 0.12, similarity_boost: 0.45, style: 0.75, use_speaker_boost: true },
  encouragement: { stability: 0.16, similarity_boost: 0.50, style: 0.65, use_speaker_boost: true },
  question:      { stability: 0.20, similarity_boost: 0.55, style: 0.55, use_speaker_boost: true },
  emphasis:      { stability: 0.16, similarity_boost: 0.50, style: 0.60, use_speaker_boost: true },
  thinking:      { stability: 0.24, similarity_boost: 0.60, style: 0.35, use_speaker_boost: true },
  statement:     { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true },
  instruction:   { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true }
};

function readEnvKey() {
  if (process.env.VITE_ELEVENLABS_API_KEY) return process.env.VITE_ELEVENLABS_API_KEY;
  for (const f of ['.env.local', '.env']) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    const m = fs.readFileSync(p, 'utf8').match(/^\s*VITE_ELEVENLABS_API_KEY\s*=\s*"?([^"\r\n]+)"?/m);
    if (m) return m[1].trim();
  }
  return '';
}

const slugify = text =>
  text.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 50);

const sleep = ms => new Promise(r => setTimeout(r, ms));

function cleanForSpeech(text) {
  return text
    .replace(/\$(\d+[\d,]*(\.\d+)?)/g, '$1 dollars')
    .replace(/(\d+)%/g, '$1 percent')
    .replace(/−/g, ' minus ')
    .replace(/÷/g, ' divided by ')
    .replace(/×/g, ' times ')
    .replace(/²/g, ' squared')
    .replace(/³/g, ' cubed')
    .replace(/\s+/g, ' ')
    .trim();
}

function writeMapFile(map) {
  const out =
    '/* =========================================================================\n' +
    '   AUTO-GENERATED by scripts/generate_audio.js — do not edit by hand.\n' +
    '   Key: exact spoken text  →  Value: pre-generated MP3 path.\n' +
    '   ========================================================================= */\n' +
    `export const audioMap = ${JSON.stringify(map, null, 2)};\n`;
  fs.writeFileSync(MAP_FILE, out);
}

async function main() {
  const apiKey = readEnvKey();
  if (!apiKey) {
    console.error('✖ No API key found in .env.local');
    process.exit(1);
  }

  // Read existing map
  let map = {};
  if (fs.existsSync(MAP_FILE)) {
    try {
      const content = fs.readFileSync(MAP_FILE, 'utf8');
      const m = content.match(/audioMap\s*=\s*(\{[\s\S]*?\});/);
      if (m) map = JSON.parse(m[1]);
    } catch (e) {}
  }

  // The 75 phrases that previously used fallback
  const indices = [
    1, 89, 109, 137, 139,
    ...Array.from({ length: 10 }, (_, i) => 140 + i),
    ...Array.from({ length: 20 }, (_, i) => 180 + i),
    ...Array.from({ length: 20 }, (_, i) => 200 + i),
    ...Array.from({ length: 20 }, (_, i) => 220 + i)
  ];

  console.log(`Regenerating ${indices.length} phrases with ElevenLabs Alice (${VOICE_ID})...`);
  let successCount = 0;

  for (let i = 0; i < indices.length; i++) {
    const idx = indices[i];
    const p = ALL_PHRASES[idx - 1];
    const hash = crypto.createHash('md5').update(p.text).digest('hex').slice(0, 6);
    const fileName = `audio_${slugify(p.text)}_${hash}.mp3`;
    const filePath = path.join(OUT_DIR, fileName);
    const publicPath = `/assets/audio/${fileName}`;

    const spokenText = cleanForSpeech(p.text);
    const s = STYLE_SETTINGS[p.style] || STYLE_SETTINGS.statement;

    let success = false;
    for (let attempt = 1; attempt <= 3; attempt++) {
      try {
        const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
          method: 'POST',
          headers: {
            'xi-api-key': apiKey,
            'Content-Type': 'application/json',
            Accept: 'audio/mpeg'
          },
          body: JSON.stringify({
            text: spokenText,
            model_id: MODEL_ID,
            voice_settings: s
          })
        });

        if (!res.ok) {
          const err = await res.text();
          throw new Error(`${res.status}: ${err}`);
        }

        const buf = Buffer.from(await res.arrayBuffer());
        fs.writeFileSync(filePath, buf);
        map[p.text] = publicPath;
        success = true;
        successCount++;
        console.log(`[${i + 1}/${indices.length}] (Idx ${idx}) ✔ ${p.text.slice(0, 40)}… (${buf.length} bytes)`);
        break;
      } catch (e) {
        console.log(`[${i + 1}/${indices.length}] Attempt ${attempt} failed: ${e.message.slice(0, 80)}`);
        await sleep(1500 * attempt);
      }
    }

    if (!success) {
      console.error(`✖ Failed to regenerate phrase ${idx}: ${p.text.slice(0, 40)}`);
    }

    // Rate-limit throttle to avoid hitting concurrent/minute limits
    await sleep(400);

    if ((i + 1) % 10 === 0) writeMapFile(map);
  }

  writeMapFile(map);
  console.log(`\nDone! Successfully regenerated ${successCount} / ${indices.length} phrases with ElevenLabs Alice.`);
}

main();

